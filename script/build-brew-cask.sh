#!/usr/bin/env bash
cd "$(dirname "$0")/.."
source ./script/setup.sh

# Writes .release/nanopress.rb, the cask for https://github.com/emrecaglarid/homebrew-tap. The zip it points at is the
# one attached to the GitHub release of the same version

zip_file='' # mandatory
build_version='' # mandatory
while test $# -gt 0; do
    case $1 in
        --build-version) build_version="$2"; shift 2;;
        --zip-file) zip_file="$2"; shift 2;;
        *) echo "Unknown arg $1"; exit 1;;
    esac
done

if ! test -f "$zip_file"; then echo "--zip-file must point to the release zip" > /dev/stderr; exit 1; fi
if test -z "$build_version"; then echo "--build-version is mandatory" > /dev/stderr; exit 1; fi

sha=$(shasum -a 256 "$zip_file" | awk '{print $1}')

mkdir -p .release
cat > .release/nanopress.rb <<CASK
cask "nanopress" do # THE FILE IS GENERATED BY build-brew-cask.sh
  version "$build_version"
  sha256 "$sha"

  url "https://github.com/emrecaglarid/nanopress/releases/download/v#{version}/nanopress-v#{version}.zip"
  name "nanopress"
  desc "Tiling window manager for macOS that you use with the mouse"
  homepage "https://github.com/emrecaglarid/nanopress"

  depends_on macos: :ventura # macOS 13

  # nanopress isn't notarized. Without this, macOS refuses to open it
  postflight do
    system_command "/usr/bin/xattr", args: ["-d", "com.apple.quarantine", "#{staged_path}/nanopress-v#{version}/bin/nanopress"], must_succeed: false
    system_command "/usr/bin/xattr", args: ["-d", "com.apple.quarantine", "#{appdir}/nanopress.app"], must_succeed: false
  end

  app "nanopress-v#{version}/nanopress.app"
  binary "nanopress-v#{version}/bin/nanopress"

  zap trash: [
    "~/Library/Application Support/io.github.emrecaglarid.nanopress",
    "~/Library/Preferences/io.github.emrecaglarid.nanopress.plist",
  ]
end
CASK
